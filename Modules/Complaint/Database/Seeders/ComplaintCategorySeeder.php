    protected function seedCategories(array $items, ?int $parentId, int $level): void
    {
        foreach ($items as $index => $item) {
            $category = ComplaintCategory::updateOrCreate(
                [
                    'parent_id' => $parentId,
                    'title' => $item['title'],
                ],
                [
                    'level' => $level,
                    'sort_order' => $index + 1,
                    'is_active' => true,
                ]
            );

            if (! empty($item['children'])) {
                $this->seedCategories($item['children'], $category->id, $level + 1);
            }
        }
    }
