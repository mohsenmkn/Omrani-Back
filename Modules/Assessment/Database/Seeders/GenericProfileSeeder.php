    public function run(): void
    {
        $profiles = $this->getGenericProfiles();

        foreach ($profiles as $profileData) {
            $post = AssessmentPost::updateOrCreate(
                [
                    'title'  => $profileData['title'],
                    'grade'  => $profileData['grade'],
                    'source' => 'auto',
                ],
                [
                    'unit'      => null,
                    'domain'    => null,
                    'is_active' => true,
                ]
            );

            // حذف سوالات قبلی این پست
            AssessmentQuestion::where('post_id', $post->id)->delete();

            $sortOrder = 0;

            foreach ($profileData['questions'] as $question) {
                $category = AssessmentCategory::where('title', $question['category'])->first();

                if (!$category) {
                    $this->command->warn("⚠️ دسته یافت نشد: {$question['category']}");
                    continue;
                }

                AssessmentQuestion::create([
                    'post_id'        => $post->id,
                    'category_id'    => $category->id,
                    'title'          => $question['title'],
                    'required_score' => $question['score'] ?? 5,
                    'risk_level'     => null,
                    'fix_deadline'   => null,
                    'sort_order'     => $sortOrder++,
                    'is_active'      => true,
                ]);
            }

            $this->command->info("✅ شناسنامه «{$profileData['title']}» — " . count($profileData['questions']) . " سوال");
        }
    }

